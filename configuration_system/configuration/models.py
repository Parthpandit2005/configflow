from dataclasses import dataclass, field
from typing import Optional


@dataclass
class ProjectInfo:
    """
    Basic information about the project.
    """

    name: str
    customer: Optional[str] = None
    project_number: Optional[str] = None


@dataclass
class ProjectInput:
    """
    Structured input provided by the engineer/UI.

    This is the official input contract for the
    configuration engine.
    """

    project: ProjectInfo
    requirements: list[str] = field(default_factory=list)


@dataclass
class ConfigurationMapping:
    """
    PLC ↔ PC mapping for a parameter.
    """

    access_type: Optional[str]
    plc_parameter_name: Optional[str]
    pc_parameter_name: Optional[str]


@dataclass
class ConfigurationParameter:
    """
    A parameter required by the generated configuration.
    """

    id: int
    name: str
    data_type: Optional[str]
    description: Optional[str]

    # Why this parameter exists
    source_requirements: list[str] = field(
        default_factory=list
    )

    # PLC / PC mappings
    mappings: list[ConfigurationMapping] = field(
        default_factory=list
    )


@dataclass
class ConfigurationSummary:
    """
    Summary information about the generated configuration.
    """

    requirements_count: int
    parameters_count: int


@dataclass
class ConfigurationOutput:
    """
    Final structured configuration generated by the engine.
    """

    project: ProjectInfo
    requirements: list[str]

    parameters: list[ConfigurationParameter]

    summary: ConfigurationSummary